// Bundle the browser half into the single file dsh loads.
//
// dsh does not import a plugin's client code as a module: it evaluates one script that calls
// `window.__ModuleLoader__.load({ id, factory })`, and the factory receives dsh's own `require` for the modules the app
// already has (React, its icon set). So the bundle is CommonJS text wrapped in that call, and `react` stays external —
// shipping a second copy of React would break hooks across the two trees.
import { build } from 'esbuild';
import { readFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const out = join(root, 'dist', 'web', 'client.js');

mkdirSync(dirname(out), { recursive: true });

await build({
  entryPoints: [join(root, 'src', 'web', 'index.ts')],
  outfile: out,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120'],
  logLevel: 'warning',
  legalComments: 'none',
  // dsh's loader supplies these; bundling React would double it.
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  banner: {
    js: [
      '/* dsh-widgets — generated by build.web.mjs. Do not edit; edit src/web and run `npm run build`. */',
      'window.__ModuleLoader__.load({',
      `  id: ${JSON.stringify(pkg.name)},`,
      '  factory(require) {',
      '    var module = { exports: {} };',
      '    var exports = module.exports;',
      '    try {',
    ].join('\n'),
  },
  footer: {
    js: [
      '    } catch (error) {',
      // A factory that throws leaves dsh saying only "entry did not activate"; the reason goes to the console instead.
      `      console.error('${pkg.name}: the client half failed to load', error);`,
      '      throw error;',
      '    }',
      '    return module.exports;',
      '  }',
      '});',
    ].join('\n'),
  },
});

// The loader matches the factory by id, and a wrong id is a silent "plugin never loaded", so it is checked here.
const text = readFileSync(out, 'utf8');
const expected = `id: ${JSON.stringify(pkg.name)},`;
if (!text.includes(expected)) {
  throw new Error(`dist/web/client.js does not register the plugin as ${pkg.name}`);
}
if (!text.includes('factory(require)')) throw new Error('dist/web/client.js lost its factory wrapper');
if (text.includes('node:')) throw new Error('dist/web/client.js imports a node: module, which the browser cannot have');

const bytes = Buffer.byteLength(text);
console.log(`dist/web/client.js  ${(bytes / 1024).toFixed(1)} kB  id=${pkg.name}`);